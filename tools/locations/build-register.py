"""Reproducibly extract factual location names from official public registers.

Usage: python build-register.py ONS_2021.pdf JO_2026_25.pdf JO_2026_40.pdf
Requires pypdf. Output is generated TypeScript reference data, not executable policy.
Commune keys retain the ONS 2021 identity; they do NOT claim to be new 2026 codes.
"""
import hashlib
import json
import re
import sys
import unicodedata
from pathlib import Path
from pypdf import PdfReader

baseline, territory, names = map(Path, sys.argv[1:])
lines = [line for page in PdfReader(baseline).pages[3:] for line in page.extract_text().splitlines()]
communes = [list(m.groups()) for line in lines if (m := re.match(r"^(.+?)\s+(\d{2})\s+(\d{2})\s+(.+?)\s*$", line))]
wilayas = [list(m.groups()) for line in lines if (m := re.match(r"^([^\d]+?)\s+(\d{2})\s+([^\d]+?)\s*$", line))]
assert len(communes) == len({w + c for _, w, c, _ in communes}) == 1541
assert len(wilayas) == 58
# PDF text extraction reverses 51 in the Ouled Djellal heading; the rendered page/table show 51.
# Bordj Badji Mokhtar's heading wraps over two lines; use its complete commune name.
assert wilayas[50][0] == 'OULED DJELLAL' and wilayas[50][1] == '15'
wilayas[50][1] = '51'
wilayas[49][0] = 'BORDJ BADJI MOKHTAR'
assert [w[1] for w in wilayas] == [f'{i:02}' for i in range(1, 59)]

def norm(value):
    return re.sub('[^a-z]', '', unicodedata.normalize('NFKD', value.lower()))

# Explicit spelling equivalences between ONS 2021 and JO 26-06, restricted to each parent.
# No fuzzy match is accepted during generation.
aliases = {
    'elbeidha': 'beidha', 'hadjmechri': 'hadjmecheri',
    'abdelkaderazil': 'azilabdelkader', 'mdoukal': 'amdoukel', 'djemourah': 'djemorah',
    'eloglaelmelha': 'eloglaelmalha', 'zmaletelemirabdelkader': 'zmaletelemiraek',
    'serguine': 'serghine', 'ainouessara': 'ainoussera', 'bouiralahdab': 'bouiralahdeb',
    'sidiladjel': 'sidilaadjel', 'faidhelbotma': 'feidhelbotma', 'oumlaadham': 'oumladham',
    'chelaleteladhaoura': 'chellaleteladhaoura', 'oumeldjallil': 'oumeldjalil',
    'boughezoul': 'boughzoul', 'mouhamedboudiaf': 'mohamedboudiaf', 'birfoda': 'birfodda',
    'menaa': 'menea', 'ainelmeleh': 'ainelmelh', 'oultem': 'oulten',
    'arbaouat': 'arbaouet', 'elmeharra': 'elmehara',
}
law = '\n'.join(p.extract_text() for p in PdfReader(territory).pages[7:9])
groups = re.split(r'« Art\. 52[.]?\s*[Bb]is \d+[.]?', law)[1:]
parents = ['03','05','07','12','13','14','17','17','26','28','32']
counts = [12,8,5,4,4,6,10,8,21,23,7]
assert len(groups) == 11
memberships = {}
for index, (parent, group, count) in enumerate(zip(parents, groups, counts), 59):
    members = re.findall(r'^\d+\.\s+(.+?)(?: ;|\. »)', group.split('Art. 4.')[0], re.M)
    assert len(members) == count
    for offset, member in enumerate(members):
        key = aliases.get(norm(member), norm(member))
        matches = [c for c in communes if c[1] == parent and norm(c[0]) == key]
        assert len(matches) == 1, (parent, member, matches)
        row = matches[0]
        identity = row[1] + row[2]
        assert identity not in memberships
        memberships[identity] = f'{index:02}'
        if offset == 0:
            wilayas.append([member, f'{index:02}', row[3]])
assert len(memberships) == 108
decree = '\n'.join(p.extract_text() for p in PdfReader(names).pages[4:5])
for name, code, _ in wilayas[58:]:
    assert re.search(rf'{code}- Wilaya', decree), code
    assert norm(name) in norm(decree), name

data = {
    'version': 'dz-ons2021-jo2026-v1',
    'sources': [
        {'url': url, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
        for url, path in zip([
            'https://www.ons.dz/IMG/pdf/code_geo_2021.pdf',
            'https://www.joradp.dz/FTP/jo-francais/2026/F2026025.pdf',
            'https://www.joradp.dz/FTP/jo-francais/2026/F2026040.pdf',
        ], [baseline, territory, names])
    ],
    'wilayas': [[code, fr.strip(), ar.strip()] for fr, code, ar in wilayas],
    'communes': [[f'ons2021-{w}{c}', memberships.get(w+c, w), fr.strip(), ar.strip()] for fr,w,c,ar in communes],
}
assert len(data['wilayas']) == 69 and len({c[1] for c in data['communes']}) == 69
output = Path(__file__).resolve().parents[2] / 'packages/backend/commerce/src/algeria-register.generated.ts'
output.write_text('// Generated by tools/locations/build-register.py from official factual registers.\n'
                  '// Commune keys preserve ONS 2021 identity, not an invented 2026 code.\n'
                  'export const algeriaRegister = ' + json.dumps(data, ensure_ascii=False, indent=2) + ' as const;\n')
print(f'Generated {len(wilayas)} wilayas / {len(communes)} communes; {len(memberships)} reassigned.')
